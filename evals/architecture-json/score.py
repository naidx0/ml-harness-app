"""Score a persisted run on the two metrics that mean something here.

BOOKKEEPING OVER A HARNESS RESULT, NOT A SECOND TEST HARNESS. Every answer this
reads was generated by `measure_baseline` through the engine, driven by the
attached model. Nothing here puts a model in front of anything; it reads rows
the harness already produced and scored, and applies the two metrics the
exact-match grader cannot express.

WHY EXACT MATCH CANNOT BE USED. It scored 0 of 20 on every arm, including runs
whose output was valid and largely correct, because exact-matching a serialised
graph measures key ordering and id spelling. That is the metric being wrong
rather than the model.

THE TWO METRICS, REPORTED SEPARATELY AND NEVER POOLED.

  schema_valid  does the answer parse and satisfy evals/architecture-json/schema.json
  label_f1      set overlap of node labels against the reference

A model that emits perfect JSON about the wrong system and one that describes
the right system in prose are opposite failures. One number would call them
equal, so there is no total.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import jsonschema

HERE = Path(__file__).parent


def load_reference() -> dict[str, dict]:
    """Keyed by the DESCRIPTION rather than the whole input.

    The few-shot arm carries a different instruction on every row, so keying on
    the full input would match nothing and silently score zero -- a join that
    fails is indistinguishable from a model that failed, which is the shape of
    fault this project keeps meeting. The description is what the two arms
    share.
    """
    reference: dict[str, dict] = {}
    for name in ("held-out.jsonl", "held-out-fewshot.jsonl"):
        path = HERE / name
        if not path.exists():
            continue
        for line in path.open(encoding="utf-8"):
            if not line.strip():
                continue
            row = json.loads(line)
            reference[str(row["row_id"])] = row
    return reference


def f1(got: set[str], want: set[str]) -> float:
    hit = len(got & want)
    if not hit:
        return 0.0
    precision = hit / len(got)
    recall = hit / len(want)
    return 2 * precision * recall / (precision + recall)


def score(path: Path, schema: dict, reference: dict[str, dict]) -> dict:
    rows = [json.loads(line) for line in path.open(encoding="utf-8") if line.strip()]
    parses = valid = 0
    scores: list[float] = []
    unmatched = 0
    for row in rows:
        want = reference.get(str(row.get("row_index")))
        if want is None:
            unmatched += 1
            continue
        try:
            answer = json.loads(row["answer"])
            parses += 1
        except (ValueError, TypeError):
            scores.append(0.0)
            continue
        try:
            jsonschema.validate(answer, schema)
            valid += 1
        except jsonschema.ValidationError:
            pass
        labels = {
            str(node.get("label", "")).strip().lower()
            for node in (answer.get("nodes") or [])
            if isinstance(node, dict)
        }
        scores.append(f1(labels, set(want["node_labels"])))
    graded = len(scores)
    return {
        "file": path.name,
        "rows": len(rows),
        "graded": graded,
        "unmatched": unmatched,
        "parses": parses,
        "schema_valid": valid,
        "label_f1": (sum(scores) / graded) if graded else 0.0,
    }


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("runs", nargs="+", help="persisted run files from measure_baseline")
    args = ap.parse_args()

    schema = json.loads((HERE / "schema.json").read_text(encoding="utf-8"))
    reference = load_reference()

    print("file                                     n  parses  schema  labelF1  unmatched")
    for name in args.runs:
        row = score(Path(name), schema, reference)
        print(
            row["file"][:38].ljust(38)
            + str(row["graded"]).rjust(4)
            + (str(row["parses"]) + "/" + str(row["graded"])).rjust(8)
            + (str(row["schema_valid"]) + "/" + str(row["graded"])).rjust(8)
            + (str(round(100 * row["label_f1"])) + "%").rjust(9)
            + str(row["unmatched"]).rjust(11)
        )
        # A row that could not be joined to a reference is NOT a row that scored
        # zero, and printing it in the same column would make a broken join look
        # like a bad model.
        if row["unmatched"]:
            print("    " + str(row["unmatched"]) + " row(s) matched no reference and were "
                  "left out rather than scored zero.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
