"""The rows that take the held-out set past the resolution floor.

WHY THIS FILE EXISTS, IN THE HARNESS'S OWN WORDS. `measure_baseline` scored
minicpm5-hermes at 47% on the first 36 rows and said, unprompted:

    "36 rows put this score between 32% and 63% with 95% confidence (+-15.5
    points). Two separate runs on a set this size cannot be told apart unless
    they differ by about 23 points. To resolve a 10-point difference this way
    you would need 193 rows, which is 157 more than you have."

A target of 0.80 had already been set against a 0.47 baseline - an 18-point
lift, UNDER the 23-point floor of the set it was set on. So the number would
not have been defensible however the training went, and the honest move is more
rows rather than a louder claim. 193 is the harness's figure, not a guess.

THESE ARE HELD OUT AND NOTHING TRAINS ON THEM. They are also written before any
training data exists, which is the only order in which a result means anything.

THE FOUR FAMILIES ARE UNCHANGED, because changing what is measured while
growing how much is measured would make the new number incomparable with the
old one. Every row here is the same shape as a row in `build_held_out.py`, and
the same guards run over all of them: no answer may appear inside its own
question (except the selection family, where every candidate must), and the
"always answer the last component named" shortcut must not pass.
"""

