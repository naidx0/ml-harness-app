"""What granite4-hermes CALLS each `source: inspect` fact, harvested.

A DATA FILE, NOT A TEST. Nothing here asserts. The next phase loads it.

## Why this file exists, in one measurement

`provenance._reading_subjects()` builds the wall's subject vocabulary by
splitting each `source: inspect` fact key on its underscores, so the wall knows
`disk_free_gb` as *"disk free"*. The model writes *"Free Disk Space: 500 GB"* -
the same fact, the words in the other order. THE WALL KNOWS THE LEDGER'S NAME
FOR EACH FACT AND NOT ENGLISH'S.

Measured here through `provenance._reading_subjects` and `provenance._Words`,
counting a line as READ when it names a subject phrase at all - the purely
lexical half, BEFORE `_reads_the_subject` decides whether a nearby number is
actually a reading of it. These are upper bounds on reach, not verdicts:

    lines naming a subject phrase    derived only     + the aliases below
    HARVESTED_FABRICATIONS (112)       5 of 112           36 of 112
    FABRICATIONS (52)                 28 of 52            44 of 52
    HONEST (636)                      35 of 636          110 of 636

THE THIRD ROW IS THE PRICE, AND IT IS WHY EVERY ALIAS CARRIES ITS HONEST COUNT.
Widening the vocabulary widens what the wall reads in BOTH banks. The honest
corpus is stopped 0 times out of 636 by the wall as it stands today - measured
through `provenance.reads_as_a_measurement` against each turn's own rebuilt
Ground - and that 0 was earned at a lexical reach of 35 lines, not 110. IT DOES
NOT CARRY FORWARD. The next phase has to re-earn it at its own width, and must
report what it reads alongside what it stops.

## WHERE THE DANGER ACTUALLY IS, COUNTED

Of the 105 aliases below, **84 never appear beside a number in any of the 636
honest lines** and so cannot be misread as a reading of anything. The whole
false-catch surface is the other 21, and it is concentrated in three ordinary
English words - `gpu` (15 honest numbered lines), `vram` (12) and
`quantization` (12) - across the honest families `explains_a_method`,
`world_facts`, `hypothetical` and `restates_the_user`. `honest_with_a_number`
is the column to sort on.

AND LEXICAL REACH IS NOT A FALSE CATCH, which is the most useful thing measured
here. `vram` is ALREADY in the derived vocabulary today; it sits beside a number
in 12 honest lines; and the wall still stops 0 of 636. `_reads_the_subject`,
`_opens_hypothetically` and the wanting-clause guard are doing that work. So a
tripled reach is not a tripled false-catch rate - but it is a tripled number of
chances for those guards to be wrong, and only re-measurement can say.

## WHAT THE ATTESTATION DOES NOT PROVE, SAID OUT LOUD

A harvested line proves the model writes those WORDS. It does not always prove
the words name THAT FACT, and the difference is the soft joint in this file.
`attests` marks it on every row:

  * **`alias_and_fact`** - the line came from a fresh-harvest reply seeded with
    this fact's own ledger key, so the pairing is the model's.
  * **`alias_only`** - the line proves the words and nothing more. The three
    fabrication corpora carry no fact labels, so for every row drawn from them
    THE FACT ASSIGNMENT IS MY READING, not a measurement.

Three `alias_only` rows are worth distrusting first, and they are left in
rather than quietly dropped so the next phase can judge them:

  * `current_precision` <- *"precision"*, attested by *"3. Precision@K (top-5):
    70%"* - which is a retrieval metric, not a precision setting.
  * `baseline_score` <- *"baseline score"*, attested by *"Trivial baseline
    score: 0.50 (majority class)"* - which is the OTHER fact's line.
  * `classes_n` <- *"class balance"*, which is a different quantity from a
    count of classes.

## WHERE THE DANGER ACTUALLY IS, COUNTED

`app/provenance.py`'s docstring: "THE SUBJECT VOCABULARY IS DERIVED AND NOT
WRITTEN... This module has been burned once for writing a word list from
imagination." Every row below carries `harvested_line` - the verbatim line a
model actually wrote containing that alias. A candidate no harvested line
contained was DROPPED, and the dropped ones are named in `DROPPED_UNATTESTED`
rather than quietly deleted, because the list of words I reached for and could
not justify is the most useful audit trail in this file.

Two contaminations were found while building it, and both are worth naming,
because either would have produced a file that LOOKED harvested:

  * **The ledger key attesting itself.** A matcher joining alias words on
    `[\s\-_]+` let the key `tabular_rows` attest the "English" alias *"tabular
    rows"*, and `has_free_text_columns` attest *"free text columns"*. That is
    the ledger's own word coming back wearing a disguise - the exact failure
    the rule exists to prevent. The separator is now space-or-hyphen only, with
    identifier guards at both ends. It cost 2 rows and changed one attestation
    count from 379 to 2.
  * **The model echoing the prompt.** Several replies pasted the product's own
    instruction set back verbatim. Those lines are the HARNESS's vocabulary,
    not the model's, and attesting against one would be circular. Lines
    identical to a line of `conductor.system_prompt` or
    `conductor.standing_brief` are excluded from the fresh harvest.

## The three evidence tiers, weakest last

  * **`reported`** - the alias labels a number in a sentence the model wrote
    while REPORTING, from the three harvested fabrication banks. These are the
    sentences the wall failed to read. STRONGEST.
  * **`elicited`** - the alias labels a number in a fresh naming harvest, where
    the model was reporting the fact in one of four registers.
  * **`listed`** - the model produced the alias when ASKED to list names for the
    fact. It is a name the model wrote, but not one it was caught USING, and
    some are plainly wrong (it offered "virtual memory" for `ram_gb`). WEAKEST,
    and tagged so the next phase can take only the first two tiers.

## The fresh harvest

120 completions from `granite4-hermes:latest` on the local Ollama at
127.0.0.1:11434, under the product's own `conductor.system_prompt` and
`conductor.standing_brief`: 24 `source: inspect` facts x 5 registers - bullet,
markdown table row, plain sentence, heading, and a list of names.

THE QUESTION NEVER CONTAINED AN ENGLISH NAME FOR THE FACT. Each prompt seeds
only the LEDGER KEY - "the fact whose ledger key is `vram_gb`" - because a
question containing "video memory" would harvest my own word back out of the
model and let me call it evidence. Every English word in these rows is the
model's.
"""

